#TODO Aqui vamos ver os operadores de atribuição.

valor = 500  # Atribuição simples. O valor 10 é atribuído à variável 'valor'.

valor += 5  # Atribuição com adição. Equivalente a: valor = valor + 5. Agora 'valor' é 15.
print(valor)
valor -= 3  # Atribuição com subtração. Equivalente a: valor = valor - 3. Agora 'valor' é 12.
print(valor)
valor *= 2  # Atribuição com multiplicação. Equivalente a: valor = valor * 2. Agora 'valor' é 24.
print(valor)
valor /= 4  # Atribuição com divisão. Equivalente a: valor = valor / 4. Agora 'valor' é 6.0.
print(valor)
valor //= 2 # Atribuição com divisão inteira. Equivalente a: valor = valor // 2. Agora 'valor' é 3.0.
print(valor)
valor %= 2  # Atribuição com módulo. Equivalente a: valor = valor % 2. Agora 'valor' é 1.0.
print(valor)
valor **= 3 # Atribuição com potência. Equivalente a: valor = valor ** 3. Agora 'valor' é 1.0 (1 elevado a qualquer potência é 1).
print(valor)

