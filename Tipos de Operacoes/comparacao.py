#TODO Aqui vamos ver os operadores de comparação

laranja = 500  # Quantidade de laranjas disponíveis
comer = 600    # Quantidade de laranjas que ele quer comer

print(comer < laranja)  # Menor que (False). 600 < 500? Não, então retorna False.

print(comer > laranja)  # Maior que (True). 600 > 500? Sim, então retorna True.

print(comer <= laranja) # Menor ou igual que (False). 600 <= 500? Não, então retorna False.

print(comer >= laranja) # Maior ou igual que (True). 600 >= 500? Sim, então retorna True.

print(comer == laranja) # Igualdade (False). 600 == 500? Não são iguais, então retorna False.

print(comer != laranja) # Diferente (True). 600 != 500? Sim, são diferentes, então retorna True.


